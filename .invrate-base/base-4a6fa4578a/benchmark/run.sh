#!/usr/bin/env bash
# Paired benchmark batches: run every arm on the IDENTICAL seed list.
#
#   run.sh [--quick | --full | --count N] [--seeds FILE] [--config FILE]
#          [--arms A,B,...] [--jobs N] [--out DIR] [--server BIN]
#          [--portbase N] [--skill LEVEL]
#
#   --quick     first 10 seeds of the seed file (default)
#   --full      first 100 seeds
#   --seeds     seed list, one integer per line (default seeds/train.txt;
#               pass seeds/holdout.txt ONLY when reporting final numbers)
#   --config    game config (default configs/smoke.conf)
#   --arms      comma-separated aitypes to compare (default classic,baseline)
#   --jobs      parallel games (default: nproc)
#   --skill     run this config at another AI skill level instead of the
#               one it pins (see "Skill level" below)
#
# Results are content-addressed: they land in
# OUT/<config>-<key12>/<arm>/seed-<n>/, where the key is the sha256 of
# the config file, the server binary, and the tuning file (env TUNING,
# "none" until W25 lands). Completed games (DONE marker present) are
# skipped, so an interrupted batch resumes — and a change to the config,
# the binary, or the tuning changes the key, so stale results are never
# silently reused. OUT/<config>-<key12>/key.txt records the components.
#
# After the batch, the pairing check asserts that every arm saw the same
# map per seed (maphash.txt equality), then per-player final metrics are
# extracted to OUT/<config>-<key12>/metrics.csv (see extract.py).
#
# Skill level
# -----------
# Every .conf pins SKILL (all of them say hard, which is the level the
# whole benchmark corpus was taken at). --skill LEVEL runs the SAME cell
# at another level without editing or duplicating the .conf: it derives
# a config that differs only in the SKILL line and runs that.
#
# Deriving a file rather than passing an env var down to run-game.sh is
# what keeps the cache sound. The result key is the sha256 of the config
# file, the binary, run-game.sh and the tuning file -- an env var would
# not enter it, and a novice cell would silently cache-hit the hard
# results sitting in the same directory (the failure mode KEEP_SAVES is
# already documented for in run-game.sh). A derived file changes the
# config hash by construction, so the key changes because the game
# changed. Generation is deterministic, so a resumed run re-derives the
# identical bytes and still hits its own DONE markers, and WITHOUT
# --skill not one byte of the key computation is touched: every existing
# result dir keeps its name.
#
# Both arms of a cell -- including both modules of a mixed_XY game, which
# share one server -- get the level, because run-game.sh emits it as the
# argument-less server command that rewrites every AI player and the
# default for later ones (stdinhand.c set_ai_level()). That shared level
# is the deep-vs-stock-at-L comparison; per-seat levels would need the
# per-player command form and are not what this measures.

set -uo pipefail

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

COUNT=10
SEEDS=$here/seeds/train.txt
CONFIG=$here/configs/smoke.conf
ARMS=classic,baseline
JOBS=$(nproc 2>/dev/null || echo 4)
OUT=$here/results
SERVER=
PORTBASE=5600
SKILL=

usage() { grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --quick)  COUNT=10; shift;;
    --full)   COUNT=100; shift;;
    --count)  COUNT=$2; shift 2;;
    --seeds)  SEEDS=$2; shift 2;;
    --config) CONFIG=$2; shift 2;;
    --arms)   ARMS=$2; shift 2;;
    --jobs)   JOBS=$2; shift 2;;
    --out)    OUT=$2; shift 2;;
    --server) SERVER=$2; shift 2;;
    --portbase) PORTBASE=$2; shift 2;;
    --skill)  SKILL=$2; shift 2;;
    *) usage;;
  esac
done

[ -r "$SEEDS" ] || { echo "seed file not readable: $SEEDS" >&2; exit 1; }
[ -r "$CONFIG" ] || { echo "config not readable: $CONFIG" >&2; exit 1; }

cfgname=$(basename "$CONFIG" .conf)

# --skill: derive a config that differs from this one only in SKILL, and
# run THAT. Nothing below this block knows the difference, which is the
# point -- the derived file flows into confhash, into the key, into the
# result dir name, with no new term anywhere. Omitting --skill leaves
# every byte of that computation as it was.
if [ -n "$SKILL" ]; then
  # Only levels that are server commands, which is what run-game.sh
  # emits (server/commands.c; `away` is excluded on purpose -- it is
  # the not-playing mode, not a difficulty).
  case "$SKILL" in
    novice|easy|normal|hard|cheating|restricted|experimental) ;;
    *) echo "not an AI skill level: $SKILL" >&2; exit 1;;
  esac
  gendir=$here/configs/generated
  mkdir -p "$gendir"
  derived=$gendir/$cfgname@$SKILL.conf
  # Deterministic, so a resumed run re-derives byte-identical content and
  # keeps its own key. Written through a temp file so two concurrent
  # cells cannot read a half-written config.
  tmp=$(mktemp "$derived.XXXXXX")
  {
    echo "# GENERATED by run.sh --skill $SKILL from $cfgname.conf."
    echo "# Do not edit: regenerated, and its sha256 is the result key."
    grep -v '^SKILL=' "$CONFIG"
    echo "SKILL=$SKILL"
  } > "$tmp"
  mv -f "$tmp" "$derived"
  CONFIG=$derived
  cfgname=$cfgname@$SKILL
fi

# Content-address the result set by everything that determines a game's
# outcome besides the seed: game config, server binary, tuning file.
server_bin=${SERVER:-$here/../build/freeciv-server}
server_bin=$(readlink -f "$server_bin")
[ -r "$server_bin" ] || { echo "server not readable: $server_bin" >&2; exit 1; }
confhash=$(sha256sum "$CONFIG" | cut -d' ' -f1)
srvhash=$(sha256sum "$server_bin" | cut -d' ' -f1)
runhash=$(sha256sum "$here/run-game.sh" | cut -d' ' -f1)
if [ -n "${TUNING:-}" ]; then
  # A tuning file without the [tuning] section header loads as an EMPTY
  # override set: secfile lookups miss, every field keeps its compiled
  # default, and the run silently measures the defaults twice. That has
  # now cost one 40-game A/B (2026-08-04), which came back byte-identical
  # in both arms with the "off" arm still executing the feature. The
  # result key differs, so nothing downstream notices.
  grep -qE '^\[tuning\]' "$TUNING" || {
    echo "tuning file has no [tuning] section, so NOTHING in it would" \
         "be applied: $TUNING" >&2
    exit 1
  }
  # Same failure at key level: a name the loader never reads is a
  # silently inert line. tuning-params.ini is the registry tune-audit.py
  # checks the C side against.
  bad=$(grep -oE '^[a-z_0-9]+' "$TUNING" \
        | grep -vxFf <(grep -oE '^[a-z_0-9]+' "$here/tuning-params.ini") || true)
  [ -z "$bad" ] || {
    echo "tuning file sets keys the server does not know: $bad" >&2
    exit 1
  }
  # And the same failure one level deeper: a FLOAT tunable written
  # without a decimal point is stored by secfile as an INT entry, and
  # TUNE_DOUBLE's secfile_lookup_float_default() then falls back to the
  # COMPILED DEFAULT. The key is spelled right, the entry exists, the
  # result key differs -- and the arm silently runs the default. That
  # is how session M1 (2026-08-06) lost a 40-game pair whose two arms
  # came back bit-identical with `attack_loss_gain = 0` in one of them.
  intfloat=$(awk -F'[=,]' 'FNR==NR {if ($1 ~ /^[a-z_0-9]+/) {k=$1; gsub(/ /,"",k); t=$NF; gsub(/[ \t]/,"",t); type[k]=t} next}
                           /^[a-z_0-9]+[ \t]*=/ {k=$1; gsub(/[ \t]/,"",k); v=$2; gsub(/[ \t]/,"",v);
                                                  if (type[k]=="float" && v !~ /[.]/ && v !~ /[eE]/) print k"="v}' \
             "$here/tuning-params.ini" "$TUNING")
  [ -z "$intfloat" ] || {
    echo "tuning file writes float tunables with no decimal point, which" \
         "the loader SILENTLY ignores: $intfloat" >&2
    exit 1
  }
  tunhash=$(sha256sum "$TUNING" | cut -d' ' -f1)
else
  tunhash=none
fi
key=$(printf '%s %s %s %s\n' "$confhash" "$srvhash" "$runhash" "$tunhash" | sha256sum | cut -d' ' -f1)
cfgdir=$cfgname-${key:0:12}
mkdir -p "$OUT/$cfgdir"
{
  echo "config=$CONFIG sha256=$confhash"
  echo "server=$server_bin sha256=$srvhash"
  echo "runner=$here/run-game.sh sha256=$runhash"
  echo "tuning=${TUNING:-none} sha256=$tunhash"
} > "$OUT/$cfgdir/key.txt"

mapfile -t seeds < <(grep -E '^[0-9]+$' "$SEEDS" | head -n "$COUNT")
[ "${#seeds[@]}" -eq "$COUNT" ] || {
  echo "seed file has only ${#seeds[@]} of $COUNT requested seeds" >&2
  exit 1
}
IFS=, read -r -a arms <<< "$ARMS"

echo "config=$cfgdir arms=$ARMS seeds=${#seeds[@]} jobs=$JOBS out=$OUT"

joblist=$(mktemp)
trap 'rm -f "$joblist"' EXIT
total=0 skipped=0 port=$PORTBASE
for arm in "${arms[@]}"; do
  for seed in "${seeds[@]}"; do
    dir=$OUT/$cfgdir/$arm/seed-$seed
    total=$((total + 1))
    if [ -e "$dir/DONE" ]; then
      skipped=$((skipped + 1))
    else
      # Every concurrent server needs its own TCP port.
      printf '%s %s %s %s\n' "$seed" "$arm" "$dir" "$port" >> "$joblist"
      port=$((port + 1))
    fi
  done
done
echo "$total games; $skipped already done; $((total - skipped)) to run"

if [ -s "$joblist" ]; then
  xargs -P "$JOBS" -L 1 <"$joblist" \
    bash -c 'exec "$1" --config "$2" ${3:+--server "$3"} \
                       --seed "$4" --arm "$5" --out "$6" --port "$7"' \
    _ "$here/run-game.sh" "$CONFIG" "$SERVER" || true
fi

failed=0
for arm in "${arms[@]}"; do
  for seed in "${seeds[@]}"; do
    [ -e "$OUT/$cfgdir/$arm/seed-$seed/DONE" ] || {
      echo "MISSING: $arm seed-$seed"
      failed=$((failed + 1))
    }
  done
done

# Pairing check: every arm must have seen the same map for each seed.
pairfail=0
for seed in "${seeds[@]}"; do
  ref=
  for arm in "${arms[@]}"; do
    f=$OUT/$cfgdir/$arm/seed-$seed/maphash.txt
    [ -r "$f" ] || continue
    h=$(cat "$f")
    if [ -z "$ref" ]; then
      ref=$h
    elif [ "$h" != "$ref" ]; then
      echo "PAIRING VIOLATION: seed $seed maps differ across arms"
      pairfail=$((pairfail + 1))
    fi
  done
done

# Per-player final metrics for every completed game.
extractfail=0
if ls "$OUT/$cfgdir"/*/seed-*/DONE >/dev/null 2>&1; then
  "$here/extract.py" --root "$OUT/$cfgdir" --csv "$OUT/$cfgdir/metrics.csv" \
    || extractfail=1
fi

echo "----------------------------------------------------------------"
echo "completed: $((total - failed))/$total   pairing violations: $pairfail"
if [ "$failed" -gt 0 ] || [ "$pairfail" -gt 0 ] || [ "$extractfail" -gt 0 ]; then
  exit 1
fi
