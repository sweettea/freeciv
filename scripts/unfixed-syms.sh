#!/bin/sh
# Generate ai/unfixed/unfixed_syms.h, the symbol renames for the vendored
# copy of the stock AI in ai/unfixed/ (see ai/unfixed/README).
#
# Usage: scripts/unfixed-syms.sh BUILDDIR > ai/unfixed/unfixed_syms.h
#
# BUILDDIR is a meson build directory in which the stock ai/default and
# ai/classic objects have been compiled (they live in libfc_ai.a). Every
# global symbol those objects define gets a #define to an unf_ name. The
# header is force-included into each ai/unfixed compilation unit, so the
# copies link beside the originals without the copied files changing.
#
# Regenerate only when re-vendoring from a newer ai/default: the header
# is part of the frozen module and listed in ai/unfixed/MANIFEST.sha256.

set -e

if [ $# -ne 1 ] || [ ! -f "$1/libfc_ai.a" ]; then
  echo "Usage: $0 BUILDDIR  (a meson build dir containing libfc_ai.a)" >&2
  exit 2
fi

syms=$(nm -A --defined-only -g "$1/libfc_ai.a" \
         | grep -E '(ai_default_dai[a-z]*|ai_classic_classicai)\.c\.o' \
         | awk '{ print $NF }' | LC_ALL=C sort -u)

if [ -z "$syms" ]; then
  echo "$0: no ai/default or ai/classic objects found in $1/libfc_ai.a" >&2
  exit 1
fi

cat <<'EOF'
/***********************************************************************
 Freeciv - unfixed AI symbol renames.

   Generated by scripts/unfixed-syms.sh from `nm --defined-only -g`
   over the ai/default and ai/classic objects. Force-included (-include)
   into every ai/unfixed compilation unit, so the vendored sources stay
   byte-identical to their originals while linking beside them.
***********************************************************************/
#ifndef FC__UNFIXED_SYMS_H
#define FC__UNFIXED_SYMS_H

EOF

for s in $syms; do
  echo "#define $s unf_$s"
done

cat <<'EOF'

#endif /* FC__UNFIXED_SYMS_H */
EOF
